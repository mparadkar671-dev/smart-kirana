  static async getHsnTaxSummaryData(range?: DateFilterRange) {
    const allInvoices = await db.sales_invoices.toArray();
    const activeInvoices = allInvoices.filter(
      (inv) => inv.status === 'COMPLETED' && this.isDateInRange(inv.created_at, range)
    );
    const activeInvoiceIds = new Set(activeInvoices.map((i) => i.id));

    const saleItems = (await db.sale_items.toArray()).filter((it) =>
      activeInvoiceIds.has(it.invoice_id)
    );

    const products = await db.products.toArray();
    const prodMap = new Map(products.map((p) => [p.id, p]));

    // Determine HSN and standard GST rate based on Kirana retail category
    const getCategoryTaxDetails = (cat: string): { hsn: string; rate: number } => {
      const c = cat.toLowerCase();
      if (c.includes('grain') || c.includes('pulse') || c.includes('atta') || c.includes('rice') || c.includes('dal')) {
        return { hsn: '1006', rate: 0 }; // 0% GST (Exempt Essential Staple)
      }
      if (c.includes('oil') || c.includes('ghee') || c.includes('spice') || c.includes('sugar')) {
        return { hsn: '1512', rate: 5 }; // 5% GST
      }
      if (c.includes('biscuit') || c.includes('snack') || c.includes('tea') || c.includes('beverage')) {
        return { hsn: '1905', rate: 12 }; // 12% GST
      }
      if (c.includes('soap') || c.includes('detergent') || c.includes('clean') || c.includes('toiletries')) {
        return { hsn: '3401', rate: 18 }; // 18% GST
      }
      return { hsn: '2106', rate: 5 }; // Default 5%
    };

    const taxBuckets = new Map<
      string,
      {
        hsn: string;
        category: string;
        gstRate: number;
        grossTurnover: number;
        taxableSales: number;
        cgst: number;
        sgst: number;
        totalGst: number;
        itemCount: number;
      }
    >();

    for (const it of saleItems) {
      const prod = prodMap.get(it.product_id);
      const cat = prod ? prod.category : 'General Grocery';
      const { hsn, rate } = getCategoryTaxDetails(cat);
      const key = `${hsn}_${rate}`;

      const existing = taxBuckets.get(key) || {
        hsn,
        category: cat,
        gstRate: rate,
        grossTurnover: 0,
        taxableSales: 0,
        cgst: 0,
        sgst: 0,
        totalGst: 0,
        itemCount: 0,
      };

      existing.grossTurnover += it.line_total;
      existing.itemCount += it.qty;
      taxBuckets.set(key, existing);
    }

    let totalTaxableTurnover = 0;
    let totalCgst = 0;
    let totalSgst = 0;
    let totalGstAmount = 0;
    let totalGrossSales = 0;

    const list = Array.from(taxBuckets.values()).map((b) => {
      // In inclusive Kirana retail MRP pricing: Taxable = Gross / (1 + Rate/100)
      const taxable = b.gstRate > 0 ? b.grossTurnover / (1 + b.gstRate / 100) : b.grossTurnover;
      const gstAmount = b.grossTurnover - taxable;
      const halfTax = gstAmount / 2;

      const taxableRounded = roundCurrency(taxable);
      const cgstRounded = roundCurrency(halfTax);
      const sgstRounded = roundCurrency(halfTax);
      const gstTotalRounded = roundCurrency(gstAmount);
      const grossRounded = roundCurrency(b.grossTurnover);

      totalTaxableTurnover += taxableRounded;
      totalCgst += cgstRounded;
      totalSgst += sgstRounded;
      totalGstAmount += gstTotalRounded;
      totalGrossSales += grossRounded;

      return {
        ...b,
        taxableSales: taxableRounded,
        cgst: cgstRounded,
        sgst: sgstRounded,
        totalGst: gstTotalRounded,
        grossTurnover: grossRounded,
      };
    });

    return {
      totalTaxableTurnover: roundCurrency(totalTaxableTurnover),
      totalCgst: roundCurrency(totalCgst),
      totalSgst: roundCurrency(totalSgst),
      totalGstAmount: roundCurrency(totalGstAmount),
      totalGrossSales: roundCurrency(totalGrossSales),
      hsnCategories: list,
    };
  }

