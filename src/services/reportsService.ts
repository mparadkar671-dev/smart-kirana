  // =========================================================================
  // 2. CUSTOMER KHATA AGING & RECOVERY SHEET (0-15d, 16-30d, >30d)
  // =========================================================================
  static async getCustomerKhataAgingData() {
    const customers = await db.customers.toArray();
    const activeKhata = customers.filter(
      (c) => c.id !== '0000-WALK-IN' && c.current_udhari_balance > 0
    );

    let totalOutstanding = 0;
    let totalIn0to15 = 0;
    let totalIn16to30 = 0;
    let totalInAbove30 = 0;
    let highRiskCount = 0;

    const list = activeKhata
      .map((c) => {
        const agingDays = c.oldest_unpaid_date
          ? Math.max(
              0,
              Math.floor((Date.now() - new Date(c.oldest_unpaid_date).getTime()) / (1000 * 60 * 60 * 24))
            )
          : 0;

        let riskBucket: '0-15 Days' | '16-30 Days' | '> 30 Days';
        let recoveryStatus: 'SAFE' | 'FOLLOW_UP' | 'CRITICAL_OVERDUE';

        if (agingDays <= 15) {
          riskBucket = '0-15 Days';
          recoveryStatus = c.current_udhari_balance > c.credit_limit ? 'CRITICAL_OVERDUE' : 'SAFE';
          totalIn0to15 += c.current_udhari_balance;
        } else if (agingDays <= 30) {
          riskBucket = '16-30 Days';
          recoveryStatus = c.current_udhari_balance > c.credit_limit ? 'CRITICAL_OVERDUE' : 'FOLLOW_UP';
          totalIn16to30 += c.current_udhari_balance;
        } else {
          riskBucket = '> 30 Days';
          recoveryStatus = 'CRITICAL_OVERDUE';
          totalInAbove30 += c.current_udhari_balance;
          highRiskCount++;
        }

        totalOutstanding += c.current_udhari_balance;

        return {
          id: c.id,
          name: c.name,
          phone: c.phone,
          creditLimit: c.credit_limit,
          balance: c.current_udhari_balance,
          oldestUnpaidDate: c.oldest_unpaid_date,
          agingDays,
          riskBucket,
          recoveryStatus,
        };
      })
      .sort((a, b) => b.balance - a.balance);

    return {
      totalOutstanding: roundCurrency(totalOutstanding),
      totalIn0to15: roundCurrency(totalIn0to15),
      totalIn16to30: roundCurrency(totalIn16to30),
      totalInAbove30: roundCurrency(totalInAbove30),
      highRiskCount,
      customers: list,
    };
  }

