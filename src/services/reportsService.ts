  static async getDailyGallaShiftAuditData(range?: DateFilterRange) {
    const sessions = await db.daily_galla_sessions.toArray();
    const filtered = sessions
      .filter((s) => this.isDateInRange(s.session_date, range))
      .sort((a, b) => b.session_date.localeCompare(a.session_date));

    let totalOpening = 0;
    let totalCashSales = 0;
    let totalUdhariRecovered = 0;
    let totalExpensesOut = 0;
    let totalDiscrepancy = 0;

    const list = filtered.map((s) => {
      totalOpening += s.opening_cash;
      totalCashSales += s.cash_sales_total;
      totalUdhariRecovered += s.cash_udhari_recovered;
      totalExpensesOut += s.cash_expenses_out;

      const expected = roundCurrency(
        s.opening_cash + s.cash_sales_total + s.cash_udhari_recovered - s.cash_expenses_out
      );
      const actual = s.actual_counted_cash !== undefined && s.actual_counted_cash !== null ? s.actual_counted_cash : null;
      const discrepancy = actual !== null ? roundCurrency(actual - expected) : null;

      if (discrepancy !== null) {
        totalDiscrepancy += discrepancy;
      }

      let tallyStatus = 'OPEN';
      if (actual !== null) {
        if (Math.abs(discrepancy || 0) < 0.01) {
          tallyStatus = 'BALANCED (TALLY)';
        } else if ((discrepancy || 0) > 0) {
          tallyStatus = `+₹${(discrepancy || 0).toFixed(2)} EXCESS`;
        } else {
          tallyStatus = `-₹${Math.abs(discrepancy || 0).toFixed(2)} SHORTAGE`;
        }
      }

      return {
        id: s.id,
        sessionDate: s.session_date,
        openingCash: s.opening_cash,
        cashSales: s.cash_sales_total,
        cashRecovered: s.cash_udhari_recovered,
        expensesOut: s.cash_expenses_out,
        expectedClosing: expected,
        actualCounted: actual,
        discrepancy,
        tallyStatus,
      };
    });

    return {
      totalOpening: roundCurrency(totalOpening),
      totalCashSales: roundCurrency(totalCashSales),
      totalUdhariRecovered: roundCurrency(totalUdhariRecovered),
      totalExpensesOut: roundCurrency(totalExpensesOut),
      totalDiscrepancy: roundCurrency(totalDiscrepancy),
      sessions: list,
    };
  }

