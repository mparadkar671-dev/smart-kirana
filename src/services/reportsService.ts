  // 4. SMART WHOLESALER REORDER SHEET (14-Day Sales Velocity)
  // =========================================================================
  static async getSmartWholesalerReorderData() {
    const products = await db.products.toArray();
    const fourteenDaysAgo = new Date(Date.now() - 14 * 86400000).toISOString();

    const recentInvoices = (await db.sales_invoices.toArray()).filter(
      (inv) => inv.status === 'COMPLETED' && inv.created_at >= fourteenDaysAgo
    );
    const recentInvoiceIds = new Set(recentInvoices.map((i) => i.id));

    const recentItems = (await db.sale_items.toArray()).filter((it) =>
      recentInvoiceIds.has(it.invoice_id)
    );

    // Sum recent 14-day sales qty per product
    const sales14dMap = new Map<string, number>();
    for (const it of recentItems) {
      sales14dMap.set(it.product_id, (sales14dMap.get(it.product_id) || 0) + it.qty);
    }

    let totalItemsNeedingReorder = 0;
    let totalEstimatedBudget = 0;

    const list = products.map((p) => {
      const sold14d = sales14dMap.get(p.id) || 0;
      const velocityPerDay = Math.round((sold14d / 14) * 100) / 100;

      let daysOfStockLeft = 999;
      if (velocityPerDay > 0) {
        daysOfStockLeft = Math.floor(p.current_stock / velocityPerDay);
      } else if (p.current_stock <= p.low_stock_threshold) {
        daysOfStockLeft = 0;
      }

      const isUnderThreshold = p.current_stock <= p.low_stock_threshold;
      const isUrgentVelocity = daysOfStockLeft <= 7;
      const needsReorder = isUnderThreshold || isUrgentVelocity;

      let suggestedReorderQty = 0;
      if (velocityPerDay > 0) {
        suggestedReorderQty = Math.max(
          0,
          Math.ceil(velocityPerDay * 14 + p.low_stock_threshold - p.current_stock)
        );
      } else if (isUnderThreshold) {
        suggestedReorderQty = Math.max(0, Math.ceil(p.low_stock_threshold * 2 - p.current_stock));
      }

      const estimatedCost = roundCurrency(suggestedReorderQty * p.purchase_price);

      if (needsReorder && suggestedReorderQty > 0) {
        totalItemsNeedingReorder++;
        totalEstimatedBudget += estimatedCost;
      }

      return {
        id: p.id,
        name: p.name,
        category: p.category,
        currentStock: p.current_stock,
        unitType: p.unit_type,
        lowStockThreshold: p.low_stock_threshold,
        purchasePrice: p.purchase_price,
        sold14d,
        velocityPerDay,
        daysOfStockLeft,
        needsReorder,
        suggestedReorderQty,
        estimatedCost,
        supplierName: p.last_supplier_name || 'General Wholesale Mandi',
      };
    });

    // Sort items needing reorder first
    const sorted = list.sort((a, b) => {
      if (a.needsReorder && !b.needsReorder) return -1;
      if (!a.needsReorder && b.needsReorder) return 1;
      return a.daysOfStockLeft - b.daysOfStockLeft;
    });

    return {
      totalItemsNeedingReorder,
      totalEstimatedBudget: roundCurrency(totalEstimatedBudget),
      items: sorted,
    };
  }

